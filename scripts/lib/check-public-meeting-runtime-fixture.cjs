const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { installNextServerCliBoundary } = require('./register-next-server-cli.ts');
const boundary = installNextServerCliBoundary();
const { writePublicMeetingRuntimeArtifacts } = require(path.join(process.cwd(), 'lib/public-meetings/runtime-artifacts.ts'));
const { getPublicMeetingAdminDashboard } = require(path.join(process.cwd(), 'lib/public-meetings/public.ts'));
const { getMeetingVotingCards } = require(path.join(process.cwd(), 'lib/public-meetings/voting-cards.ts'));
const { getPublicMeetingItems } = require(path.join(process.cwd(), 'lib/public-meetings/public-record-eligibility.ts'));
process.chdir(process.argv[2]);
(async () => {
  const input = JSON.parse(fs.readFileSync('inputs.json', 'utf8'));
  await writePublicMeetingRuntimeArtifacts(input);
  const base = 'data/generated/';
  assert.equal(fs.existsSync(base + 'public-meeting-items.json'), false);
  assert.equal(fs.existsSync(base + 'public-meeting-voting-cards.json'), false);
  const workerManifests = ['public-meeting-source-documents.json', 'public-meeting-document-cache-index.json', 'public-meeting-document-text.json'];
  for (const name of workerManifests) fs.writeFileSync(base + name, JSON.stringify({ records: [{ meetingId: 'meeting-public', sourceUrl: input.items[0].source_url }] }));
  const dashboardWithWorkerManifests = await getPublicMeetingAdminDashboard();
  const cardsWithWorkerManifests = await getMeetingVotingCards();
  for (const name of workerManifests) fs.unlinkSync(base + name);
  let dashboard = await getPublicMeetingAdminDashboard();
  let cards = await getMeetingVotingCards();
  assert.deepEqual(dashboard, dashboardWithWorkerManifests, 'Public meeting readers must not depend on detailed worker manifests');
  assert.deepEqual(cards, cardsWithWorkerManifests, 'Voting questions must survive without detailed worker manifests');
  assert.equal(dashboard.meetings[0].id, 'meeting-public');
  assert.deepEqual(dashboard.meetingItems.map(x => x.id), ['item-public']);
  assert.equal(dashboard.meetingItems[0].source_text.length <= 1200, true);
  assert.equal(dashboard.meetingItems[0].cached_text_path, null);
  assert.equal(dashboard.meetingItems[0].source_local_path, undefined);
  assert.equal(dashboard.meetings[0].agenda_url, input.items[0].source_url);
  assert.deepEqual(dashboard.meetings[0].source_urls, [input.items[0].source_url]);
  assert.equal(dashboard.meetingItems[0].source_url, input.items[0].source_url);
  assert.equal(dashboard.meetingItems[0].source_page, 2);
  assert.equal(cards.cards[0].source_url, input.items[0].source_url);
  assert.equal(cards.cards[0].topic_item_id, dashboard.meetingItems[0].id);
  assert.equal(cards.cards[0].meeting_id, dashboard.meetings[0].id);
  assert.deepEqual(cards.cards.map(x => x.id), ['card-public']);
  assert.ok(Array.isArray(cards.cards[0].source_snippets));
  assert.ok(Array.isArray(cards.cards[0].related_official_actions));
  assert.ok(cards.cards[0].created_at);
  assert.deepEqual(getPublicMeetingItems(input.items).map(x => x.id), dashboard.meetingItems.map(x => x.id));
  // Old compact bundles may predate the public gate; fallback still filters them.
  fs.writeFileSync(base + 'voting-cards-runtime.json', JSON.stringify([{ ...input.votingCards[0], source_snippets: undefined, related_official_actions: undefined, created_at: undefined }, input.votingCards[1]]));
  cards = await getMeetingVotingCards();
  assert.deepEqual(cards.cards.map(x => x.id), ['card-public']);
  assert.deepEqual(cards.cards[0].source_snippets, []);
  assert.deepEqual(cards.cards[0].related_official_actions, []);
  assert.equal(cards.cards[0].created_at, cards.cards[0].updated_at);
  // Full files preserve the administrator's complete review queue.
  fs.writeFileSync(base + 'public-meeting-items.json', JSON.stringify(input.items));
  fs.writeFileSync(base + 'public-meeting-voting-cards.json', JSON.stringify(input.votingCards));
  dashboard = await getPublicMeetingAdminDashboard();
  cards = await getMeetingVotingCards();
  assert.equal(dashboard.meetingItems.length, 3);
  assert.equal(cards.allCards.length, 2);
  fs.writeFileSync(base + 'public-meeting-items.json', '[]');
  fs.writeFileSync(base + 'public-meeting-voting-cards.json', '[]');
  assert.equal((await getPublicMeetingAdminDashboard()).meetingItems.length, 0);
  assert.equal((await getMeetingVotingCards()).cards.length, 0);
  console.log('runtime parity passed');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => boundary.deregister());
